"""217：存在重复元素，2026-10-22 参考复习版。

带中文注释的参考实现，供独立练习后对照复习。
集合查找和添加的平均时间为 O(1)，最多检查 n 个元素，整体平均时间为 O(n)。
额外空间最坏为 O(n)，例如列表中的所有值都不同。
如果所有值相同且至少有两个元素，检查第二个元素时就会提前返回 True。
空列表是额外的本地边界练习。
"""


def contains_duplicate(nums):  # 接收数字列表，返回是否包含重复值
    seen = set()  # seen：此前见过的数字；set() 创建空集合，{} 是空字典

    for number in nums:  # 按顺序读取列表里的每个数字
        if number in seen:  # 先检查该数字在此前是否已经出现过
            return True  # 出现过，说明存在重复，立即结束函数
        seen.add(number)  # 第一次见到，才把它加入集合

    return False  # 所有数字都检查完还没有重复；这句在循环外


if __name__ == "__main__":  # 直接运行本文件时，执行下面的七组检查
    examples = [  # 每组分别保存输入数字列表和预期的布尔结果
        ([2, 5, 2], True),  # 非相邻重复：第三个数字与第一个相同
        ([1, 2, 3, 4], False),  # 没有重复：需要检查全部数字
        ([7, 7, 7, 7], True),  # 所有值相同：第二个数字就能确定有重复
        ([7], False),  # 只有一个数字，不存在重复
        ([-1, 0, -1], True),  # 负数也能作为集合元素，按同样方式检查
        ([0, 0], True),  # 零也是普通数字，可以重复
        ([], False),  # 本地拓展：空列表没有重复，循环不会执行
    ]

    for nums, expected in examples:  # 分别取出本组输入和预期结果
        result = contains_duplicate(nums)  # 实际调用函数，获得返回值
        assert result is expected  # assert：检查返回的布尔值符合预期
        print(nums, "->", result)  # 打印本组输入与实际结果

    print("七组检查全部通过。")  # 只有全部检查成功才会执行到这里
